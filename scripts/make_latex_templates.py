#!/usr/bin/env python3
"""Generate src/np_latex_templates.c / .h from the bundled .tex files.

The templates are self-contained single-file LaTeX documents (MIT licensed,
sourced from paulinelemenkova/LaTeX-templates-classes plus one Chinese XeLaTeX
template authored for RapidEditor). Each file is stored verbatim as a C string.
The editor copies the selected template into a new untitled tab; the existing
\\documentclass/\\begin{document} sniff then turns on the LaTeX preview.

Re-run after adding or editing a template:

    python3 scripts/make_latex_templates.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TPL_DIR = os.path.join(ROOT, "assets", "latex-templates")
OUT_C = os.path.join(ROOT, "src", "np_latex_templates.c")
OUT_H = os.path.join(ROOT, "src", "np_latex_templates.h")

# (file, C identifier, display name, description, default filename). Order is menu order.
TEMPLATES = [
    ("template_article.tex", "article",
     "文章 (article)", "通用短文 / 论文，pdflatex 编译", "article.tex"),
    ("template-letter.tex", "letter",
     "信件 (letter)", "正式信函，pdflatex 编译", "letter.tex"),
    ("presentation-beamer-Madrid.tex", "beamer_madrid",
     "演示文稿 (beamer)", "带 Madrid 主题的幻灯片，pdflatex 编译", "slides.tex"),
    ("template_memoir.tex", "memoir",
     "书籍/报告 (memoir)", "长篇文档与书籍，pdflatex 编译", "memoir.tex"),
    ("template-cn-xelatex.tex", "cn_xelatex",
     "中文文档 (xelatex)", "中文正文与公式，xelatex + ctex 编译", "document-cn.tex"),
]

HEADER = """#ifndef NP_LATEX_TEMPLATES_H
#define NP_LATEX_TEMPLATES_H

/* Built-in, self-contained LaTeX templates. Each one is a complete single
 * .tex file that compiles on its own (verified with TeX Live 2024). The editor
 * copies the selected text into a new tab; no external cls/sty/image needed. */

#ifdef __cplusplus
extern "C" {
#endif

typedef struct {
    const char *name;         /* menu / dialog label */
    const char *desc;         /* one-line description */
    const char *filename;     /* suggested filename for Save As */
    const char *text;         /* full .tex source, NUL terminated */
} np_latex_template;

int np_latex_template_count(void);
const np_latex_template *np_latex_template_at(int index);

#ifdef __cplusplus
}
#endif

#endif /* NP_LATEX_TEMPLATES_H */
"""


def cstring(data: bytes) -> str:
    """Emit a UTF-8 byte string as a C string literal, one line per source line."""
    out = []
    for raw in data.split(b"\n"):
        pieces = []
        for b in raw:
            if b == 0x22:
                pieces.append('\\"')
            elif b == 0x5C:
                pieces.append("\\\\")
            elif b == 0x09:
                pieces.append("\\t")
            elif 0x20 <= b < 0x7F:
                pieces.append(chr(b))
            else:
                pieces.append("\\%03o" % b)
        out.append('        "' + "".join(pieces) + '\\n"')
    # Last split element is empty when the file ends with newline; drop its line.
    if out and out[-1].strip() == '"\\n"':
        out.pop()
    return "\n".join(out)


def main():
    decls = []
    table = []
    for fname, ident, name, desc, filename in TEMPLATES:
        with open(os.path.join(TPL_DIR, fname), "rb") as f:
            data = f.read()
        decls.append(
            "/* %s -- from %s */\nstatic const char tpl_%s[] =\n%s;\n"
            % (name, fname, ident, cstring(data))
        )
        table.append(
            '    { "%s", "%s", "%s", tpl_%s },' % (name, desc, filename, ident)
        )

    src = "/* Generated by scripts/make_latex_templates.py -- do not edit. */\n"
    src += '#include "np_latex_templates.h"\n'
    src += "#include <stddef.h>   /* NULL */\n\n"
    src += "\n".join(decls) + "\n\n"
    src += "static const np_latex_template templs[] = {\n" + "\n".join(table) + "\n};\n\n"
    src += "int np_latex_template_count(void) { return (int)(sizeof templs / sizeof templs[0]); }\n"
    src += "const np_latex_template *np_latex_template_at(int i) {\n"
    src += "    return i >= 0 && i < (int)(sizeof templs / sizeof templs[0]) ? &templs[i] : NULL;\n"
    src += "}\n"

    with open(OUT_C, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    with open(OUT_H, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
    print("wrote %s (%d templates, %d bytes)" % (OUT_C, len(TEMPLATES), len(src)))


if __name__ == "__main__":
    main()
