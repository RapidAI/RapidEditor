#!/usr/bin/env python3
"""Generate np_bt_templates.c from assets/bt-templates/*.bt.

Similar to make_latex_templates.py: embeds template sources as C string
literals so no runtime file I/O or packaging changes are needed.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC_DIR = os.path.join(ROOT, "assets", "bt-templates")
OUT = os.path.join(ROOT, "src", "np_bt_templates.c")
OUT_H = os.path.join(ROOT, "src", "np_bt_templates.h")


def c_str(s: str) -> str:
    out = []
    for ch in s.encode("utf-8"):
        if ch == ord('\n'):
            out.append("\\n")
        elif ch == ord('"'):
            out.append('\\"')
        elif ch == ord('\\'):
            out.append("\\\\")
        elif 32 <= ch < 127:
            out.append(chr(ch))
        else:
            out.append("\\%03o" % ch)
    return "".join(out)


def main():
    files = sorted(f for f in os.listdir(SRC_DIR) if f.endswith(".bt"))
    if not files:
        print("no .bt templates found", file=sys.stderr)
        return 1

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/make_bt_templates.py. Do not edit. */\n")
        f.write('#include "np_bt_templates.h"\n#include <stddef.h>\n\n')
        # Read all sources first so forward declarations can carry a size
        # (MSVC rejects an unsized `static const char x[];` redeclared later).
        entries = []
        for fn in files:
            name = os.path.splitext(fn)[0]
            with open(os.path.join(SRC_DIR, fn), "r", encoding="utf-8") as tf:
                text = tf.read()
            cname = "bt_src_" + name.replace("-", "_")
            literal = c_str(text)
            # +1 for NUL; utf-8 escapes are emitted as octal bytes (4 chars each
            # in source) but the array length counts actual bytes, so use encoded size.
            nbytes = len(text.encode("utf-8")) + 1
            f.write("static const char %s[%d];\n" % (cname, nbytes))
            entries.append((cname, text, literal))
        f.write("\nconst np_bt_builtin np_bt_builtins[] = {\n")
        for (cname, text, literal), fn in zip(entries, files):
            name = os.path.splitext(fn)[0]
            f.write('    { "%s", "%s", %s },\n' % (name, name.upper(), cname))
        f.write("    { NULL, NULL, NULL }\n")
        f.write("};\n\n")
        for cname, text, literal in entries:
            nbytes = len(text.encode("utf-8")) + 1
            f.write("static const char %s[%d] =\n" % (cname, nbytes))
            f.write('    "%s";\n\n' % literal)

    with open(OUT_H, "w", encoding="utf-8") as f:
        f.write("#ifndef NP_BT_TEMPLATES_H\n#define NP_BT_TEMPLATES_H\n\n")
        f.write("/* Built-in binary format templates (010 Editor style). */\n")
        f.write("typedef struct np_bt_builtin {\n")
        f.write("    const char *name;   /* short id, e.g. \"png\" */\n")
        f.write("    const char *label;  /* display name */\n")
        f.write("    const char *source; /* template script */\n")
        f.write("} np_bt_builtin;\n\n")
        f.write("extern const np_bt_builtin np_bt_builtins[];\n\n")
        f.write("#endif /* NP_BT_TEMPLATES_H */\n")

    print("generated %d templates -> %s" % (len(files), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
