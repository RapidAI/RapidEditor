#!/usr/bin/env python3
"""Generate src/np_font_bundle.c / .h from the bundled TTF files in assets/fonts.

Each font is stored as a raw DEFLATE stream (RFC 1951) in a C byte array. At
runtime the app unpacks it with CUI's cui__inflate() and hands the bytes to the
public cui_font_load_memory(). Keeping the data compressed keeps the executable
small (~600 KB of font data instead of ~1.4 MB).

Re-run this script after adding or replacing a font in assets/fonts/:

    python3 scripts/make_font_bundle.py
"""
import os
import struct
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FONTS_DIR = os.path.join(ROOT, "assets", "fonts")
OUT_C = os.path.join(ROOT, "src", "np_font_bundle.c")
OUT_H = os.path.join(ROOT, "src", "np_font_bundle.h")

# (file, C identifier, menu display name). Order is the menu order.
FONTS = [
    ("JetBrainsMono-Regular.ttf", "jetbrains_mono", "JetBrains Mono", "编程 · 连字"),
    ("CascadiaCode-Regular.ttf",  "cascadia_code",  "Cascadia Code",  "编程 · 连字"),
    ("CascadiaMono-Regular.ttf",  "cascadia_mono",  "Cascadia Mono",  "编程"),
    ("SourceCodePro-Regular.ttf", "source_code_pro", "Source Code Pro", "编程"),
    ("IBMPlexMono-Regular.ttf",   "ibm_plex_mono",  "IBM Plex Mono",  "编程"),
]

# Read the font's internal family name from the name table (ID 1) so the
# display label can be validated; we keep our own friendly label in the menu.
def sfnt_family(path):
    with open(path, "rb") as f:
        data = f.read()
    num = struct.unpack(">H", data[4:6])[0]
    tables = {}
    for i in range(num):
        off = 12 + i * 16
        tag = data[off:off + 4].decode("latin1")
        o, l = struct.unpack(">II", data[off + 8:off + 16])
        tables[tag] = (o, l)
    if "name" not in tables:
        return None
    o, l = tables["name"]
    count, str_off = struct.unpack(">HH", data[o + 2:o + 6])
    best = None
    for i in range(count):
        rec = o + 6 + i * 12
        platform, enc, lang, nid, ln, ofs = struct.unpack(">HHHHHH", data[rec:rec + 12])
        if nid != 1 or lang not in (0x409, 0):
            continue
        s = data[o + str_off + ofs:o + str_off + ofs + ln]
        try:
            txt = s.decode("utf-16-be" if platform == 3 else "latin1")
        except Exception:
            continue
        if best is None or platform == 3:
            best = txt
    return best


def c_bytes(data):
    """Format bytes as a C array literal, 16 per line."""
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ",".join("0x%02x" % b for b in chunk) + ",")
    return "\n".join(lines)


def main():
    entries = []
    for fname, ident, label, tag in FONTS:
        path = os.path.join(FONTS_DIR, fname)
        if not os.path.exists(path):
            raise SystemExit("missing font file: " + path)
        with open(path, "rb") as f:
            raw = f.read()
        if raw[:4] not in (b"\x00\x01\x00\x00", b"true", b"ttcf"):
            raise SystemExit("not a TrueType font: " + path)
        packed = zlib.compress(raw, 9)[2:-4]  # strip zlib header + adler32
        fam = sfnt_family(path) or label
        entries.append((ident, label, tag, fam, raw, packed))
        print("%-22s raw=%7d  deflate=%7d  family=%s" %
              (ident, len(raw), len(packed), fam))

    # ---- header ----
    h = ["/* Generated by scripts/make_font_bundle.py -- do not edit. */",
         "#ifndef NP_FONT_BUNDLE_H", "#define NP_FONT_BUNDLE_H",
         "", "#include <stddef.h>", "",
         "typedef struct np_bundled_font {",
         "    const char *ident;         /* stable id, saved in config.ini */",
         "    const char *label;         /* menu display name */",
         "    const char *tag;           /* short descriptor */",
         "    const unsigned char *data; /* raw DEFLATE stream */",
         "    size_t packed_size;        /* compressed byte count */",
         "    size_t raw_size;           /* unpacked TTF byte count */",
         "} np_bundled_font;", "",
         "extern const np_bundled_font np_bundled_fonts[];",
         "extern const int np_bundled_font_count;", "",
         "#endif /* NP_FONT_BUNDLE_H */", ""]
    with open(OUT_H, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(h))

    # ---- source ----
    c = ["/* Generated by scripts/make_font_bundle.py -- do not edit. */",
         '#include "np_font_bundle.h"', ""]
    for ident, label, tag, fam, raw, packed in entries:
        c.append("/* %s -- %s (%d bytes raw, %d bytes packed) */" %
                 (label, fam, len(raw), len(packed)))
        c.append("static const unsigned char np_font_%s[] = {" % ident)
        c.append(c_bytes(packed))
        c.append("};")
        c.append("")
    c.append("const np_bundled_font np_bundled_fonts[] = {")
    for ident, label, tag, fam, raw, packed in entries:
        c.append('    { "%s", "%s", "%s", np_font_%s, %d, %d },' %
                 (ident, label, tag, ident, len(packed), len(raw)))
    c.append("};")
    c.append("const int np_bundled_font_count = %d;" % len(entries))
    c.append("")
    with open(OUT_C, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(c))

    print("wrote %s (%d bytes)" % (OUT_C, os.path.getsize(OUT_C)))
    print("wrote %s" % OUT_H)


if __name__ == "__main__":
    main()
